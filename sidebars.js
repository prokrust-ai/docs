import rpcSidebar from './docs/reference/api/rpc/sidebar.json';
import inventory from './docs/reference/kubernetes/inventory.json';

const providers = new Map();
for (const resource of Object.values(inventory).flat()) {
  if (!resource.provider) continue;
  const group = providers.get(resource.provider) ?? [];
  group.push(resource);
  providers.set(resource.provider, group);
}

const connectorPages = [...providers.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([provider, resources]) => {
  const synthetic = provider === 'synthetic';
  const items = resources.map(({kind, version, url}) => ({
    type: 'ref', id: url.slice(1, -1), label: kind + ' (' + version + ')',
  }));
  if (synthetic) items.unshift('reference/connectors/synthetic/release-1.1.0-rc.1');
  return {
    type: 'category', label: resources[0].kind.replace(/Connection$/, ''),
    ...(synthetic && {link: {type: 'doc', id: 'reference/connectors/synthetic'}}), items,
  };
});

export default {
  handbook: [
    {type: 'category', label: 'Operator guide', items: ['operator/workspaces']},
    {
      type: 'category', label: 'User guide',
      link: {type: 'doc', id: 'user/overview'},
      items: [
        'user/core-concepts',
        {
          type: 'category', label: 'How-to Guides',
          link: {type: 'generated-index', slug: '/user/how-to-guides', title: 'How-to Guides'},
          items: ['user/create-a-table', 'user/synthetic-table'],
        },
      ],
    },
    {
      type: 'category', label: 'Reference Doc', link: {type: 'doc', id: 'reference/overview'},
      items: [
        {type: 'category', label: 'Connectors',
          link: {type: 'generated-index', slug: '/reference/connectors', title: 'Connectors'},
          items: connectorPages},
        {type: 'category', label: 'Kubernetes resources', items: [{type: 'autogenerated', dirName: 'reference/kubernetes'}]},
        {type: 'category', label: 'Public API', link: {type: 'doc', id: 'reference/api/rpc/index'},
          items: [
            ...rpcSidebar,
            {type: 'category', label: 'HTTP endpoints', link: {type: 'doc', id: 'reference/api/http/index'},
              items: ['web-session', 'performance', 'inference', 'web-health', 'operator-metrics'].map(id => 'reference/api/http/' + id)},
          ]},
      ],
    },
  ],
};
